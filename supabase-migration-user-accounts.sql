  -- Run this once in Supabase: SQL Editor -> New query -> Run.
  -- Creates user profiles and admin-only account management functions.

  create table if not exists public.user_profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    full_name text not null check (char_length(trim(full_name)) between 2 and 80),
    email text not null,
    is_active boolean not null default true,
    created_at timestamptz not null default now()
  );

  create table if not exists public.account_audit_log (
    id bigint generated by default as identity primary key,
    actor_id uuid references auth.users(id) on delete set null,
    target_user_id uuid references auth.users(id) on delete set null,
    action text not null check (action in (
      'user_enabled', 'user_disabled', 'admin_granted', 'admin_revoked',
      'user_deleted', 'admin_access_approved', 'admin_access_rejected'
    )),
    details jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
  );

  alter table public.account_audit_log enable row level security;

  create or replace function public.is_active_user()
  returns boolean language sql stable security definer set search_path = public as $$
    select exists (
      select 1 from public.user_profiles
      where id = auth.uid() and is_active
    );
  $$;

  revoke all on function public.is_active_user() from public;
  grant execute on function public.is_active_user() to authenticated;

  drop policy if exists "Admins can view account audit log" on public.account_audit_log;
  create policy "Admins can view account audit log"
  on public.account_audit_log for select to authenticated
  using (
    (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
    and public.is_active_user()
  );

  create or replace function public.audit_account_action(
    action_name text,
    target_id uuid,
    action_details jsonb default '{}'::jsonb
  )
  returns void language sql security definer set search_path = public as $$
    insert into public.account_audit_log(actor_id, target_user_id, action, details)
    values (auth.uid(), target_id, action_name, coalesce(action_details, '{}'::jsonb));
  $$;

  revoke all on function public.audit_account_action(text, uuid, jsonb) from public;

  alter table public.user_profiles enable row level security;

  drop policy if exists "Users can view their own profile" on public.user_profiles;
  create policy "Users can view their own profile"
  on public.user_profiles for select to authenticated
  using (auth.uid() = id and public.is_active_user());

  create or replace function public.sync_user_profile_email()
  returns trigger language plpgsql security definer set search_path = public as $$
  begin
    update public.user_profiles
    set email = lower(new.email)
    where id = new.id and new.email is distinct from old.email;
    return new;
  end;
  $$;

  drop trigger if exists on_auth_user_email_changed on auth.users;
  create trigger on_auth_user_email_changed
  after update of email on auth.users
  for each row execute function public.sync_user_profile_email();

  create or replace function public.require_campus_email()
  returns trigger language plpgsql security definer set search_path = public as $$
  begin
    if new.email is null or lower(new.email) not like '%@lnmiit.ac.in' then
      raise exception 'Use a verified LNMIIT campus email address';
    end if;
    return new;
  end;
  $$;

  drop trigger if exists on_auth_user_campus_email on auth.users;
  create trigger on_auth_user_campus_email
  before insert on auth.users
  for each row execute function public.require_campus_email();

  create or replace function public.create_user_profile()
  returns trigger language plpgsql security definer set search_path = public as $$
  begin
    insert into public.user_profiles (id, full_name, email)
    values (
      new.id,
      coalesce(nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''), 'Campus user'),
      lower(new.email)
    );
    return new;
  end;
  $$;

  create or replace function public.admin_list_admins()
  returns table (id uuid, full_name text, email text, created_at timestamptz)
  language sql security definer set search_path = public as $$
    select
      u.id,
      coalesce(p.full_name, u.raw_user_meta_data ->> 'full_name', 'Campus user'),
      coalesce(p.email, u.email),
      u.created_at
    from auth.users u
    left join public.user_profiles p on p.id = u.id
    where (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
      and u.raw_app_meta_data ->> 'role' = 'admin'
      and public.is_active_user()
    order by u.created_at asc;
  $$;

  create or replace function public.admin_list_account_audit()
  returns table (
    action text,
    actor_email text,
    target_email text,
    details jsonb,
    created_at timestamptz
  )
  language sql security definer set search_path = public as $$
    select l.action, actor.email, target.email, l.details, l.created_at
    from public.account_audit_log l
    left join auth.users actor on actor.id = l.actor_id
    left join auth.users target on target.id = l.target_user_id
    where (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
      and public.is_active_user()
    order by l.created_at desc
    limit 100;
  $$;

  drop trigger if exists on_auth_user_created on auth.users;
  create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.create_user_profile();

  insert into public.user_profiles (id, full_name, email)
  select
    u.id,
    coalesce(nullif(trim(u.raw_user_meta_data ->> 'full_name'), ''), 'Campus user'),
    lower(u.email)
  from auth.users u
  on conflict (id) do update set email = excluded.email;

  drop function if exists public.admin_list_user_profiles();
  create function public.admin_list_user_profiles()
  returns table (id uuid, full_name text, email text, is_active boolean, is_admin boolean, created_at timestamptz, last_sign_in_at timestamptz)
  language sql security definer set search_path = public as $$
    select p.id, p.full_name, p.email, p.is_active,
      (u.raw_app_meta_data ->> 'role') = 'admin' as is_admin,
      p.created_at,
      u.last_sign_in_at
    from public.user_profiles p
    join auth.users u on u.id = p.id
    where (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
    and public.is_active_user()
    order by p.created_at desc;
  $$;

  create or replace function public.admin_set_user_admin(target_user_id uuid, make_admin boolean)
  returns void language plpgsql security definer set search_path = public as $$
  begin
    if (auth.jwt() -> 'app_metadata' ->> 'role') <> 'admin' or not public.is_active_user() then
      raise exception 'Only admins can manage user accounts';
    end if;
    if target_user_id = auth.uid() and not make_admin then
      raise exception 'Admins cannot remove their own admin access';
    end if;
    if not make_admin and (
      select count(*) from auth.users
      where raw_app_meta_data ->> 'role' = 'admin'
    ) <= 1 then
      raise exception 'The last administrator cannot be removed';
    end if;
    update auth.users
    set raw_app_meta_data = case
      when make_admin then coalesce(raw_app_meta_data, '{}'::jsonb) || '{"role":"admin"}'::jsonb
      else coalesce(raw_app_meta_data, '{}'::jsonb) - 'role'
    end
    where id = target_user_id;
    perform public.audit_account_action(
      case when make_admin then 'admin_granted' else 'admin_revoked' end,
      target_user_id
    );
  end;
  $$;

  create or replace function public.admin_set_user_active(target_user_id uuid, active boolean)
  returns void language plpgsql security definer set search_path = public as $$
  begin
    if (auth.jwt() -> 'app_metadata' ->> 'role') <> 'admin' or not public.is_active_user() then
      raise exception 'Only admins can manage user accounts';
    end if;
    if target_user_id = auth.uid() and not active then
      raise exception 'Admins cannot disable their own account';
    end if;
    update public.user_profiles
    set is_active = active
    where id = target_user_id;
    perform public.audit_account_action(
      case when active then 'user_enabled' else 'user_disabled' end,
      target_user_id
    );
  end;
  $$;

  create or replace function public.admin_delete_user(target_user_id uuid)
  returns void language plpgsql security definer set search_path = public as $$
  begin
    if (auth.jwt() -> 'app_metadata' ->> 'role') <> 'admin' or not public.is_active_user() then
      raise exception 'Only admins can manage user accounts';
    end if;
    if target_user_id = auth.uid() then
      raise exception 'Admins cannot delete their own account';
    end if;
    perform public.audit_account_action('user_deleted', target_user_id);
    delete from auth.users where id = target_user_id;
  end;
  $$;

  grant execute on function public.admin_list_user_profiles() to authenticated;
  grant execute on function public.admin_list_admins() to authenticated;
  grant execute on function public.admin_list_account_audit() to authenticated;
  grant execute on function public.admin_set_user_admin(uuid, boolean) to authenticated;
  grant execute on function public.admin_set_user_active(uuid, boolean) to authenticated;
  grant execute on function public.admin_delete_user(uuid) to authenticated;
  grant select on public.account_audit_log to authenticated;
